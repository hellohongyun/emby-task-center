/** Regenerate packaged PNG after editing the built-in SVG; Node 24 + Playwright. */
import { chromium } from "@playwright/test";
import { writeFile } from "node:fs/promises";
import { DEFAULT_LIBRARY_POSTER_SVG } from "@emby-task-center/contracts/library-poster";

const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 960, height: 540 }, deviceScaleFactor: 1 });
  await page.setContent(
    `<style>html,body{margin:0;background:#101c31}svg{display:block}</style>${DEFAULT_LIBRARY_POSTER_SVG}`,
  );
  await page.evaluate(() => document.fonts.ready);
  const png = await page.screenshot({ type: "png" });
  await writeFile(
    new URL("../packages/contracts/src/library-poster-png.ts", import.meta.url),
    `// Generated by scripts/generate-library-poster.mjs from library-poster.ts.\nexport const DEFAULT_LIBRARY_POSTER_PNG_BASE64 =\n  ${JSON.stringify(png.toString("base64"))};\n`,
  );
} finally {
  await browser.close();
}
