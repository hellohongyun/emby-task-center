import { createServer, type Server } from "node:http";
import type { AddressInfo } from "node:net";
import { afterEach, describe, expect, it } from "vitest";
import { createDatabase } from "@emby-task-center/database/client";
import { createVirtualLibraryStore } from "./store";
import { createVirtualProxyHandler } from "./proxy-handler";
import { libraryDto } from "./library-dto";
const png = Buffer.from(
  "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/l7sAAAAASUVORK5CYII=",
  "base64",
);
const servers: Server[] = [];
const databases: ReturnType<typeof createDatabase>[] = [];
async function listen(server: Server) {
  servers.push(server);
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  return "http://127.0.0.1:" + (server.address() as AddressInfo).port;
}
afterEach(async () => {
  for (const server of servers.splice(0)) {
    server.closeAllConnections();
    await new Promise<void>((resolve) => server.close(() => resolve()));
  }
  for (const database of databases.splice(0)) database.close();
});
async function fixture() {
  const database = createDatabase(":memory:");
  databases.push(database);
  const store = createVirtualLibraryStore(database.db);
  const library = store.create({ name: "Custom cover" });
  store.setPoster(library.id, png, "image/png");
  const observed: { path: string; token: string }[] = [];
  const upstream = await listen(
    createServer((request, response) => {
      observed.push({ path: request.url!, token: String(request.headers["x-emby-token"] ?? "") });
      if (request.headers["x-emby-token"] !== "client-token") {
        response.writeHead(401, { "content-type": "text/plain" }).end("denied");
        return;
      }
      if (request.url?.includes("/Images/")) {
        response.writeHead(200, { "content-type": "image/jpeg" }).end("original-image");
        return;
      }
      response
        .writeHead(200, { "content-type": "application/json" })
        .end(JSON.stringify({ Items: [], TotalRecordCount: 0 }));
    }),
  );
  const base = await listen(createServer(createVirtualProxyHandler(store, () => upstream, "poster-test")));
  return { base, store, library, observed };
}
describe("owned custom posters through HTTP proxy", () => {
  it("serves each advertised image type with original client auth, stable bytes and HEAD", async () => {
    const { base, store, library, observed } = await fixture();
    const dto = libraryDto(store, library.id);
    const poster = store.getPoster(library.id)!;
    expect(dto).toMatchObject({
      ImageTags: { Primary: poster.imageTag, Thumb: poster.imageTag },
      BackdropImageTags: [poster.imageTag],
      PrimaryImageAspectRatio: 1,
    });
    for (const type of ["Primary", "Thumb", "Backdrop/0"]) {
      const response = await fetch(base + "/emby/Items/" + library.id + "/Images/" + type, {
        headers: { "x-emby-token": "client-token" },
      });
      expect(response.status).toBe(200);
      expect(response.headers.get("content-type")).toBe("image/png");
      expect(Buffer.from(await response.arrayBuffer())).toEqual(png);
    }
    const url = base + "/Items/" + library.id + "/Images/Primary";
    const head = await fetch(url, { method: "HEAD", headers: { "x-emby-token": "client-token" } });
    expect(head.headers.get("content-length")).toBe(String(png.length));
    expect(await head.text()).toBe("");
    const cached = await fetch(url, {
      headers: { "x-emby-token": "client-token", "if-none-match": head.headers.get("etag")! },
    });
    expect(cached.status).toBe(304);
    expect(observed).toHaveLength(5);
    expect(observed.every((entry) => !entry.path.includes("/Images/") && entry.token === "client-token")).toBe(true);
  });
  it("supports the tokenless tagged image URLs generated by Emby web without an upstream probe", async () => {
    const { base, store, library, observed } = await fixture();
    const tag = store.getPoster(library.id)!.imageTag;
    const url = `${base}/emby/Items/${library.id}/Images/Primary?tag=${tag}&maxWidth=400`;
    const response = await fetch(url, {
      headers: { accept: "image/avif,image/webp,image/apng,image/*,*/*;q=0.8" },
    });
    expect(response.status).toBe(200);
    expect(Buffer.from(await response.arrayBuffer())).toEqual(png);
    const head = await fetch(url, { method: "HEAD" });
    expect(head.status).toBe(200);
    expect(head.headers.get("content-length")).toBe(String(png.length));
    const cached = await fetch(url, { headers: { "if-none-match": head.headers.get("etag")! } });
    expect(cached.status).toBe(304);
    expect(observed).toEqual([]);
  });
  it("requires client authentication for missing or stale tags, including conditional requests", async () => {
    const { base, store, library } = await fixture();
    const response = await fetch(base + "/Items/" + library.id + "/Images/Primary", {
      headers: { "if-none-match": '"' + store.getPoster(library.id)!.imageTag + '"' },
    });
    expect(response.status).toBe(401);
    expect(await response.text()).toBe("denied");
    const stale = await fetch(`${base}/Items/${library.id}/Images/Primary?tag=stale`);
    expect(stale.status).toBe(401);
  });
  it("leaves original image IDs untouched", async () => {
    const { base, observed } = await fixture();
    const response = await fetch(base + "/emby/Items/native/Images/Primary?tag=original&maxWidth=600", {
      headers: { "x-emby-token": "client-token" },
    });
    expect(await response.text()).toBe("original-image");
    expect(observed).toEqual([
      { path: "/emby/Items/native/Images/Primary?tag=original&maxWidth=600", token: "client-token" },
    ]);
  });
});
